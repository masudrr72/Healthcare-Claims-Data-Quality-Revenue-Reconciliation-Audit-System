    "PROCEDURES" INTEGER,
    "NPI" TEXT
);

CREATE TABLE IF NOT EXISTS raw.payers (
    "Id" TEXT PRIMARY KEY,
    "NAME" TEXT,
    "OWNERSHIP" TEXT,
    "ADDRESS" TEXT,
    "CITY" TEXT,
    "STATE_HEADQUARTERED" TEXT,
    "ZIP" TEXT,
