    "Id" TEXT PRIMARY KEY,
    "ORGANIZATION" TEXT,
    "NAME" TEXT,
    "GENDER" TEXT,
    "SPECIALITY" TEXT,
    "ADDRESS" TEXT,
    "CITY" TEXT,
    "STATE" TEXT,
    "ZIP" TEXT,
